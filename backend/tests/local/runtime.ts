import 'dotenv/config';
import assert from 'node:assert/strict';
import { randomUUID, createHash } from 'node:crypto';
import { Pool } from 'pg';
import { readFileSync } from 'node:fs';
import { obtenerConfiguracionS3 } from '../../src/config/s3.config.js';
import { generarUrlPresigned } from '../../src/core/storage/s3-storage.service.js';
const base = process.env.BASE_URL ?? 'http://localhost:3000';
const ready = await fetch(base+'/ready');
assert.equal(ready.status,200);
const pool = new Pool({connectionString:process.env.DATABASE_URL});
try {
  const estado = (await pool.query('SELECT current_database() AS db, (SELECT count(*)::int FROM sigd_migraciones) AS migraciones')).rows[0];
  console.log('DB real:',JSON.stringify(estado));
  assert.equal(estado.db,'sigd_prueba'); assert.equal(estado.migraciones,13);
  const tipos = await fetch(base+'/api/v1/tramites/tipos');
  assert.equal(tipos.status,200); assert.ok(Array.isArray(await tipos.json()));
  const credentials=readFileSync('.env.demo.local','utf8');
  const identificador=credentials.match(/^DEMO_USER=(.+)$/m)![1],password=credentials.match(/^DEMO_PASSWORD=(.+)$/m)![1];
  const login=await fetch(base+'/api/v1/auth/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({identificador,password})});
  assert.equal(login.status,200);
  const token=(await login.json() as {accessToken:string}).accessToken;
  const bandeja = await fetch(base+'/api/v1/expedientes?pestana=PENDIENTES',{headers:{authorization:'Bearer '+token}});
  assert.equal(bandeja.status,200);
  const pagina = await bandeja.json() as {elementos:unknown[];contadores:Record<string,number>};
  assert.ok(Array.isArray(pagina.elementos)); assert.equal(Object.keys(pagina.contadores).length,6);
  console.log('PASS: /ready, catalogo TUPA y bandeja HTTP con consulta real:',JSON.stringify(pagina));
  const sinToken = await fetch(base+'/api/v1/expedientes?pestana=PENDIENTES'); assert.equal(sinToken.status,401);
  const noExiste = await fetch(base+'/api/v1/expedientes/'+randomUUID(),{headers:{authorization:'Bearer '+token}}); assert.equal(noExiste.status,404);
  const contenido = Buffer.from('%PDF-1.4\nSIGD local S3 verification\n%%EOF');
  const config=obtenerConfiguracionS3();
  const key=process.env.S3_PERSISTENCE_KEY!; assert.ok(key);
  const persistente=await fetch(generarUrlPresigned(key,config)); assert.equal(persistente.status,200);
  assert.equal(createHash('sha256').update(Buffer.from(await persistente.arrayBuffer())).digest('hex'),createHash('sha256').update(contenido).digest('hex'));
  console.log('PASS: objeto S3 mantiene SHA-256 despues de reiniciar almacenamiento');
  const presign=await fetch(base+'/api/v1/storage/presigned-url',{method:'POST',headers:{'content-type':'application/json',authorization:'Bearer '+token},body:JSON.stringify({nombreArchivo:'local.pdf',tamanoBytes:contenido.length,mimeType:'application/pdf',sha256Hash:createHash('sha256').update(contenido).digest('hex')})});
  assert.equal(presign.status,200); const subida=await presign.json() as {uploadUrl:string;s3Key:string};
  const put=await fetch(subida.uploadUrl,{method:'PUT',headers:{'content-type':'application/pdf'},body:contenido});assert.equal(put.ok,true,await put.text());
  console.log('PASS: URL PUT emitida por API permite almacenar PDF real:',subida.s3Key);
  console.log('Usuarios locales existentes:',(await pool.query('SELECT count(*)::int AS n FROM sigd_auth.cuenta_usuario')).rows[0].n);
} finally { await pool.end(); }
