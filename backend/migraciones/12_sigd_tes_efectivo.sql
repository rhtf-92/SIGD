END $$;
ALTER TABLE sigd_tes.pago ADD CONSTRAINT pago_verificacion CHECK(estado<>'VERIFICADO' OR (verificado_por IS NOT NULL AND verificado_en IS NOT NULL));
ALTER TABLE sigd_tes.pago ADD CONSTRAINT pago_efectivo CHECK(
 (caja_id IS NULL AND efectivo_recibido IS NULL AND vuelto IS NULL AND importe_aplicado IS NULL)
 OR (caja_id IS NOT NULL AND medio='CAJA' AND efectivo_recibido IS NOT NULL AND importe_aplicado IS NOT NULL AND vuelto IS NOT NULL AND importe_aplicado>0 AND vuelto>=0 AND efectivo_recibido=importe_aplicado+vuelto));
ALTER TABLE sigd_tes.devolucion ADD CONSTRAINT devolucion_aprobacion CHECK(aprobada_por IS NULL OR (evaluada_por IS NOT NULL AND aprobada_por<>ciudadano_id));
ALTER TABLE sigd_tes.ejecucion_devolucion ADD COLUMN caja_id uuid REFERENCES sigd_tes.caja(id), ADD COLUMN demostracion boolean NOT NULL DEFAULT false;
CREATE TABLE sigd_tes.movimiento_caja (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), caja_id uuid NOT NULL REFERENCES sigd_tes.caja(id),
 tipo varchar(16) NOT NULL CHECK(tipo IN('INGRESO','DEVOLUCION')), importe numeric(14,2) NOT NULL CHECK(importe>0),
 pago_id uuid UNIQUE REFERENCES sigd_tes.pago(id), ejecucion_id uuid UNIQUE REFERENCES sigd_tes.ejecucion_devolucion(id),
 actor_id uuid NOT NULL REFERENCES sigd_auth.cuenta_usuario(id_usuario), creado_en timestamptz NOT NULL DEFAULT clock_timestamp(),
 CHECK((tipo='INGRESO' AND pago_id IS NOT NULL AND ejecucion_id IS NULL) OR (tipo='DEVOLUCION' AND ejecucion_id IS NOT NULL AND pago_id IS NULL))
);
CREATE INDEX movimiento_caja_fecha ON sigd_tes.movimiento_caja(caja_id,creado_en);
CREATE FUNCTION sigd_tes.proteger_caja() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
 IF TG_OP IN('DELETE','TRUNCATE') OR TG_TABLE_NAME='movimiento_caja' THEN RAISE EXCEPTION 'Movimiento de caja inmutable' USING ERRCODE='23001'; END IF;
 IF OLD.cerrada_en IS NOT NULL OR (to_jsonb(NEW)-ARRAY['cerrada_por','cerrada_en','efectivo_contado','saldo_esperado','diferencia','observaciones']) IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['cerrada_por','cerrada_en','efectivo_contado','saldo_esperado','diferencia','observaciones']) THEN
  RAISE EXCEPTION 'Apertura/cierre de caja inmutable' USING ERRCODE='23001'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER proteger_caja BEFORE UPDATE OR DELETE ON sigd_tes.caja FOR EACH ROW EXECUTE FUNCTION sigd_tes.proteger_caja();
CREATE TRIGGER proteger_caja_truncate BEFORE TRUNCATE ON sigd_tes.caja FOR EACH STATEMENT EXECUTE FUNCTION sigd_tes.proteger_caja();
CREATE TRIGGER proteger_movimiento BEFORE UPDATE OR DELETE ON sigd_tes.movimiento_caja FOR EACH ROW EXECUTE FUNCTION sigd_tes.proteger_caja();
CREATE TRIGGER proteger_movimiento_truncate BEFORE TRUNCATE ON sigd_tes.movimiento_caja FOR EACH STATEMENT EXECUTE FUNCTION sigd_tes.proteger_caja();
