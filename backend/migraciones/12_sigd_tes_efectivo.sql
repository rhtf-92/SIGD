CREATE TABLE sigd_tes.caja (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), clave_solicitud uuid NOT NULL UNIQUE,
 abierta_por uuid NOT NULL REFERENCES sigd_auth.cuenta_usuario(id_usuario), abierta_en timestamptz NOT NULL DEFAULT clock_timestamp(),
 saldo_inicial numeric(14,2) NOT NULL CHECK(saldo_inicial>=0), demostracion boolean NOT NULL,
 cerrada_por uuid REFERENCES sigd_auth.cuenta_usuario(id_usuario), cerrada_en timestamptz,
 efectivo_contado numeric(14,2) CHECK(efectivo_contado>=0), saldo_esperado numeric(14,2), diferencia numeric(14,2), observaciones varchar(2000),
 CHECK((cerrada_en IS NULL AND cerrada_por IS NULL AND efectivo_contado IS NULL AND saldo_esperado IS NULL AND diferencia IS NULL)
 OR (cerrada_en IS NOT NULL AND cerrada_por IS NOT NULL AND efectivo_contado IS NOT NULL AND saldo_esperado IS NOT NULL AND diferencia IS NOT NULL AND diferencia=efectivo_contado-saldo_esperado AND observaciones IS NOT NULL AND length(trim(observaciones))>=10))
);
CREATE UNIQUE INDEX caja_unica_abierta ON sigd_tes.caja((true)) WHERE cerrada_en IS NULL;
ALTER TABLE sigd_tes.pago ADD COLUMN caja_id uuid REFERENCES sigd_tes.caja(id),
 ADD COLUMN efectivo_recibido numeric(14,2), ADD COLUMN vuelto numeric(14,2), ADD COLUMN importe_aplicado numeric(14,2),
 ADD COLUMN numero_recibo bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 ADD COLUMN demostracion boolean NOT NULL DEFAULT false;
