 (origen_catalogo_sha256 ~ '^[0-9a-f]{64}$' AND creada_por IS NULL AND validada_por IS NULL AND estado='VALIDADA' AND validada_en IS NOT NULL)
 OR (origen_catalogo_sha256 IS NULL AND evidencia_id IS NOT NULL AND creada_por IS NOT NULL AND
